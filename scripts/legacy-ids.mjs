// Write deploy/nginx/legacy-ids.map: old Joomla article number -> new URL.
// nginx uses it for old links that only carry the number, for example
// /index.php?option=com_content&view=article&id=237 or /some/category/237-old-title.html.
// Run after adding content with a legacyId: node scripts/legacy-ids.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const rows = new Map();
function scan(dir, toUrl) {
  for (const entry of fs.readdirSync(dir, { recursive: true })) {
    if (!entry.endsWith("index.md")) continue;
    const text = fs.readFileSync(path.join(dir, entry), "utf8");
    const id = text.match(/^legacyId:\s*(\d+)/m)?.[1];
    if (id) rows.set(Number(id), toUrl(path.dirname(entry)));
  }
}
scan(path.join(root, "src/content/tutorials"), (d) => `/tutorials/${d}.html`);
scan(path.join(root, "src/content/pages"), (d) => `/${d}.html`);

// The Python bindings tutorial has no article number in its old URL; 100 is a placeholder
rows.delete(100);
const lines = [...rows].sort((a, b) => a[0] - b[0]).map(([id, url]) => `${id} ${url};`);
fs.writeFileSync(path.join(root, "deploy/nginx/legacy-ids.map"),
  "# Generated by scripts/legacy-ids.mjs: Joomla article number -> new URL\n" + lines.join("\n") + "\n");
console.log(lines.length, "article numbers");
